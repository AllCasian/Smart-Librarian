from dataclasses import dataclass
from typing import Literal


@dataclass(frozen=True)
class RetrievedBook:
    """
    Represents one book returned by semantic search.
    """

    book_id: str
    title: str
    author: str
    document: str
    distance: float

@dataclass(frozen=True)
class BookRecommendation:
    """
    Represents the recommendation generated by the LLM.
    """

    title: str
    author: str
    reason: str

@dataclass(frozen=True)
class ChatMessage:
    """
    Represents one visible message from the conversation.
    """

    role: Literal["user", "assistant"]
    content: str

@dataclass(frozen=True)
class RecommendationResult:
    """
    Contains the complete result of the recommendation flow.
    """

    title: str
    author: str
    summary: str
    answer: str

@dataclass(frozen=True)
class BookSummaryResult:
    """
    Contains the validated result of the summary tool.
    """

    title: str
    author: str
    summary: str
    serialized_content: str